"use client";

import Link from "next/link";
import { useEffect, useState } from "react";

import type { CitedBy, PaperSummary, Reference } from "@/lib/api-types";

const SHOW = 25;

/** Structured summary (problem, method, datasets, results), generated on first view and cached. */
export function SummaryCard({ arxivId }: { arxivId: string }) {
  const [summary, setSummary] = useState<PaperSummary | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    fetch(`/api/papers/${arxivId}/summary`)
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(`HTTP ${r.status}`))))
      .then((s: PaperSummary) => setSummary(s))
      .catch((e) => setError(e instanceof Error ? e.message : "failed"));
  }, [arxivId]);

  return (
    <section className="rounded-lg border border-border p-4 text-sm leading-relaxed">
      <h2 className="mb-2 text-xs font-semibold uppercase tracking-wide text-muted-foreground">Summary</h2>
      {!summary ? (
        <p className="text-muted-foreground">{error ? `Summary unavailable (${error}).` : "Summarizing…"}</p>
      ) : (
        <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1.5">
          <dt className="font-medium">Problem</dt>
          <dd>{summary.problem}</dd>
          <dt className="font-medium">Method</dt>
          <dd>{summary.method}</dd>
          {summary.datasets.length > 0 && (
            <>
              <dt className="font-medium">Datasets</dt>
              <dd>{summary.datasets.join(", ")}</dd>
            </>
          )}
          <dt className="font-medium">Results</dt>
          <dd>{summary.results}</dd>
        </dl>
      )}
      {summary && (
        <p className="mt-2 text-xs text-muted-foreground">
          Generated by {summary.model} from the {summary.source === "full_text" ? "full text" : "abstract only"}; may
          contain errors.
        </p>
      )}
    </section>
  );
}

export function useReferences(arxivId: string) {
  const [data, setData] = useState<{ references: Reference[]; cited_by: CitedBy[] } | null>(null);
  useEffect(() => {
    fetch(`/api/papers/${arxivId}/references`)
      .then((r) => (r.ok ? r.json() : null))
      .then(setData)
      .catch(() => setData(null));
  }, [arxivId]);
  return data;
}

export function ReferenceList({ refs }: { refs: Reference[] }) {
  const [all, setAll] = useState(false);
  if (!refs.length) return <p className="text-sm text-muted-foreground">No parsed bibliography (full text not fetched yet).</p>;
  const inCorpus = refs.filter((r) => r.in_corpus).length;
  return (
    <div className="flex flex-col gap-2 text-sm">
      <p className="text-xs text-muted-foreground">
        {refs.length} references · {inCorpus} in this corpus (linked)
      </p>
      <ol className="flex flex-col gap-1.5">
        {(all ? refs : refs.slice(0, SHOW)).map((r) => (
          <li key={r.position} className="flex gap-2">
            <span className="w-7 shrink-0 text-right text-muted-foreground tabular-nums">{r.position}.</span>
            <span className="min-w-0">
              {r.in_corpus && r.resolved_id ? (
                <Link href={`/papers/${r.resolved_id}`} className="hover:underline">
                  {r.resolved_title}
                </Link>
              ) : (
                <span className={r.title ? undefined : "text-muted-foreground"}>{r.title ?? r.raw_text ?? "(unparsed reference)"}</span>
              )}
              {(r.resolved_year ?? r.year) && <span className="text-muted-foreground"> ({r.resolved_year ?? r.year})</span>}
              {r.in_corpus && <span className="text-xs text-muted-foreground"> · {r.full_text ? "full text" : "abstract"}</span>}
            </span>
          </li>
        ))}
      </ol>
      {refs.length > SHOW && !all && (
        <button onClick={() => setAll(true)} className="self-start text-xs underline underline-offset-2">
          Show all {refs.length}
        </button>
      )}
    </div>
  );
}

export function CitedByList({ items }: { items: CitedBy[] }) {
  const [all, setAll] = useState(false);
  if (!items.length) return <p className="text-sm text-muted-foreground">No full-text paper in this corpus cites it yet.</p>;
  return (
    <div className="flex flex-col gap-2 text-sm">
      <p className="text-xs text-muted-foreground">
        {items.length} papers in this corpus cite it (counted from papers whose full text has been parsed)
      </p>
      <ul className="flex flex-col gap-1.5">
        {(all ? items : items.slice(0, SHOW)).map((p) => (
          <li key={p.arxiv_id}>
            <Link href={`/papers/${p.arxiv_id}`} className="hover:underline">
              {p.title}
            </Link>
            <span className="text-muted-foreground"> ({p.year})</span>
            {p.fulltext_citations > 0 && (
              <span className="text-xs text-muted-foreground"> · cited by {p.fulltext_citations}</span>
            )}
          </li>
        ))}
      </ul>
      {items.length > SHOW && !all && (
        <button onClick={() => setAll(true)} className="self-start text-xs underline underline-offset-2">
          Show all {items.length}
        </button>
      )}
    </div>
  );
}

export function Tabs<T extends string>({ tabs, value, onChange }: {
  tabs: { id: T; label: string }[]; value: T; onChange: (t: T) => void;
}) {
  return (
    <div role="tablist" className="flex gap-1 border-b border-border text-sm">
      {tabs.map((t) => (
        <button key={t.id} role="tab" aria-selected={value === t.id} onClick={() => onChange(t.id)}
          className={`-mb-px border-b-2 px-3 py-1.5 ${value === t.id ? "border-foreground font-medium" : "border-transparent text-muted-foreground hover:text-foreground"}`}>
          {t.label}
        </button>
      ))}
    </div>
  );
}
